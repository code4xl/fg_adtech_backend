#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

/**
 * Setup script for Ocean Ads SDK Integration
 * This script helps configure the connection between the SDK project and backend
 */

const ENVIRONMENTS = {
  development: {
    SDK_BUILD_PATH: '../ocean-ads-sdk-v2/dist/ocean-ads.min.js',
    CDN_BASE_URL: 'http://localhost:3000/cdn',
    CDN_INCLUDE_DEBUG: 'true',
    CDN_MINIFY: 'false',
    CDN_COMPRESSION: 'false',
    SDK_WATCH_MODE: 'true',
    CDN_VERBOSE_LOGGING: 'true',
    CDN_HOT_RELOAD: 'true',
  },
  production: {
    SDK_BUILD_PATH: './node_modules/@ocean-ads/sdk/dist/ocean-ads.min.js',
    CDN_BASE_URL: 'https://programmatic-adtech-backend.atharvajadhav.dev',
    CDN_INCLUDE_DEBUG: 'false',
    CDN_MINIFY: 'true',
    CDN_COMPRESSION: 'true',
    SDK_WATCH_MODE: 'false',
    CDN_VERBOSE_LOGGING: 'false',
    CDN_HOT_RELOAD: 'false',
    CDN_STORAGE_TYPE: 's3',
  },
  docker: {
    SDK_BUILD_PATH: '/app/shared/sdk/ocean-ads.min.js',
    CDN_BASE_URL: 'http://localhost:3000/cdn',
    CDN_STORAGE_PATH: '/app/cdn-files',
    CDN_INCLUDE_DEBUG: 'true',
    CDN_MINIFY: 'false',
    CDN_COMPRESSION: 'false',
  },
};

function log(message, level = 'info') {
  const colors = {
    info: '\x1b[36m',
    success: '\x1b[32m',
    warning: '\x1b[33m',
    error: '\x1b[31m',
    reset: '\x1b[0m',
  };
  console.log(
    `${colors[level]}[${level.toUpperCase()}] ${message}${colors.reset}`,
  );
}

function createEnvFile(environment) {
  const config = ENVIRONMENTS[environment];
  if (!config) {
    log(`Unknown environment: ${environment}`, 'error');
    return false;
  }

  const envContent = [
    `# Ocean Ads SDK Integration - ${environment.toUpperCase()} Environment`,
    `# Generated by setup-sdk-integration.js on ${new Date().toISOString()}`,
    '',
    '# ============================================',
    '# SDK Configuration',
    '# ============================================',
    '',
  ];

  Object.entries(config).forEach(([key, value]) => {
    envContent.push(`${key}=${value}`);
  });

  const filename = `.env.${environment}`;
  fs.writeFileSync(filename, envContent.join('\n'));
  log(`Created ${filename}`, 'success');
  return true;
}

function checkSdkProject() {
  const sdkPath = '../ocean-ads-sdk-v2';

  try {
    const packagePath = path.join(sdkPath, 'package.json');
    if (fs.existsSync(packagePath)) {
      const packageJson = JSON.parse(fs.readFileSync(packagePath, 'utf8'));
      log(
        `Found SDK project: ${packageJson.name} v${packageJson.version}`,
        'success',
      );

      // Check if dist directory exists
      const distPath = path.join(sdkPath, 'dist');
      if (fs.existsSync(distPath)) {
        const files = fs.readdirSync(distPath);
        log(`SDK build files: ${files.join(', ')}`, 'info');
      } else {
        log(
          'SDK dist directory not found. Please build the SDK project first.',
          'warning',
        );
      }
      return true;
    }
  } catch (error) {
    log(`Error checking SDK project: ${error.message}`, 'error');
  }

  log('SDK project not found at ../ocean-ads-sdk-v2', 'warning');
  return false;
}

function createSymlink() {
  try {
    const targetDir = './dist/sdk';
    const targetFile = path.join(targetDir, 'ocean-ads.min.js');
    const sourceFile = path.resolve(
      '../ocean-ads-sdk-v2/dist/ocean-ads.min.js',
    );

    // Create target directory
    if (!fs.existsSync(targetDir)) {
      fs.mkdirSync(targetDir, { recursive: true });
      log('Created dist/sdk directory', 'success');
    }

    // Remove existing symlink/file
    if (fs.existsSync(targetFile)) {
      fs.unlinkSync(targetFile);
    }

    // Create symlink
    fs.symlinkSync(sourceFile, targetFile);
    log('Created symlink to SDK file', 'success');

    return true;
  } catch (error) {
    log(`Failed to create symlink: ${error.message}`, 'error');
    return false;
  }
}

function validateConfiguration() {
  log('Validating SDK integration configuration...', 'info');

  const issues = [];

  // Check if CDN module exists
  if (!fs.existsSync('./src/cdn/cdn.module.ts')) {
    issues.push('CDN module not found');
  }

  // Check if configuration is updated
  const configPath = './src/config/configuration.ts';
  if (fs.existsSync(configPath)) {
    const configContent = fs.readFileSync(configPath, 'utf8');
    if (!configContent.includes('cdn:')) {
      issues.push('Configuration not updated with CDN settings');
    }
  }

  if (issues.length > 0) {
    log('Configuration issues found:', 'warning');
    issues.forEach((issue) => log(`  - ${issue}`, 'warning'));
    return false;
  }

  log('Configuration validation passed', 'success');
  return true;
}

function runTests() {
  log('Running SDK integration tests...', 'info');

  try {
    // Test if we can resolve the SDK path
    const configPath = require.resolve('./src/config/configuration.ts');
    log('Configuration module loads successfully', 'success');

    // Test if CDN services exist
    const cdnGenPath = './src/cdn/services/cdn-generator.service.ts';
    if (fs.existsSync(cdnGenPath)) {
      log('CDN generator service found', 'success');
    }

    return true;
  } catch (error) {
    log(`Test failed: ${error.message}`, 'error');
    return false;
  }
}

function showUsage() {
  console.log(`
Ocean Ads SDK Integration Setup

Usage:
  node scripts/setup-sdk-integration.js <command> [options]

Commands:
  setup <env>     Create environment configuration for <env> (development|production|docker)
  symlink         Create a symlink to the SDK build file
  check           Check SDK project and integration status
  validate        Validate the current configuration
  test            Run integration tests
  help            Show this help message

Examples:
  node scripts/setup-sdk-integration.js setup development
  node scripts/setup-sdk-integration.js symlink
  node scripts/setup-sdk-integration.js check
`);
}

// Main execution
function main() {
  const [, , command, ...args] = process.argv;

  log('Ocean Ads SDK Integration Setup', 'info');
  log('================================', 'info');

  switch (command) {
    case 'setup':
      const environment = args[0];
      if (!environment) {
        log(
          'Please specify an environment: development, production, or docker',
          'error',
        );
        process.exit(1);
      }
      createEnvFile(environment);
      log(`Environment ${environment} configured successfully!`, 'success');
      log(`Next steps:`, 'info');
      log(`  1. Copy .env.${environment} to .env`, 'info');
      log(
        `  2. Build your SDK project: cd ../ocean-ads-sdk-v2 && npm run build`,
        'info',
      );
      log(`  3. Start the backend: npm run start:dev`, 'info');
      break;

    case 'symlink':
      if (checkSdkProject()) {
        createSymlink();
        log('Symlink created successfully!', 'success');
      }
      break;

    case 'check':
      log('Checking SDK integration status...', 'info');
      checkSdkProject();
      validateConfiguration();
      break;

    case 'validate':
      validateConfiguration();
      break;

    case 'test':
      runTests();
      break;

    case 'help':
    default:
      showUsage();
      break;
  }
}

if (require.main === module) {
  main();
}

module.exports = {
  createEnvFile,
  checkSdkProject,
  createSymlink,
  validateConfiguration,
  runTests,
};
